export const categories: FrameCategory[] = ['All Frames', 'PixToon', 'Retro', 'Aesthetic', 'Default'];

export const getFramesByCategory = (category: FrameCategory): Frame[] => {
  if (category === 'All Frames') return frames;
  return frames.filter((frame) => frame.category === category);
};

export const getFramesByLayout = (layout: LayoutType): Frame[] => {
  return frames.filter((frame) => frame.layout === layout);
};

export const getFramesByCategoryAndLayout = (category: FrameCategory, layout: LayoutType): Frame[] => {
  let filtered = frames;
  if (category !== 'All Frames') {
    filtered = filtered.filter((frame) => frame.category === category);
  }
  return filtered.filter((frame) => frame.layout === layout);
};

export const getFrameById = (id: string): Frame | undefined => {
  return frames.find((frame) => frame.id === id);
};
